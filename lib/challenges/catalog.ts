import "server-only";

import type { Challenge, Clue, ClueType, GameMode, HistoricalEvent } from "@/types/challenge";
import type { Difficulty, Location, LocationType } from "@/types/location";

const stamp = "2026-09-01T00:00:00.000Z";

function place(input: {
  id: string;
  name: string;
  country: string;
  countryCode: string;
  region: string;
  latitude: number;
  longitude: number;
  type: LocationType;
  difficulty: Difficulty;
  description: string;
  sourceUrl?: string;
}): Location {
  return { ...input, createdAt: stamp, updatedAt: stamp };
}

function clues(items: Array<[string, ClueType]>): Clue[] {
  return items.map(([text, clueType], index) => ({
    sequence: index + 1,
    text,
    clueType,
  }));
}

function challenge(input: {
  id: string;
  mode: GameMode;
  locationId: string;
  title: string;
  difficulty: Difficulty;
  clues: Clue[];
  targetKind?: Challenge["targetKind"];
  toleranceKm?: number;
  event?: HistoricalEvent;
}): Challenge {
  const targetKind = input.targetKind ?? "exact";
  return {
    id: input.id,
    mode: input.mode,
    locationId: input.locationId,
    title: input.title,
    difficulty: input.difficulty,
    status: "published",
    targetKind,
    toleranceKm: input.toleranceKm ?? (targetKind === "approximate" ? 40 : 0),
    clues: input.clues,
    event: input.event,
    publishedAt: stamp,
    createdAt: stamp,
  };
}

